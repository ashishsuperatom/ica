// The agent template, embedded into sacli at build: every file of vm/packages/project-template/start/agent-template as
// text, by path. Generated — the folder is the one source; `pnpm build` writes this, and a test refuses a stale one.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('../../vm/packages/project-template/start/agent-template/', import.meta.url))
const OUT = fileURLToPath(new URL('../src/agent-template.gen.ts', import.meta.url))
export function collect(root = ROOT) {
  const files = {}
  const walk = (dir) => { for (const n of readdirSync(dir).sort()) { const p = join(dir, n); if (statSync(p).isDirectory()) walk(p); else files[relative(root, p).split('\\').join('/')] = readFileSync(p, 'utf8') } }
  walk(root)
  return files
}
export const render = (files) => `// GENERATED by scripts/embed-agent-template.mjs from vm/packages/project-template/start/agent-template — do not edit.\nexport const AGENT_TEMPLATE: Record<string, string> = ${JSON.stringify(files, null, 2)}\n`
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) writeFileSync(OUT, render(collect()))
